export const langs = ["fr", "en", "pt", "it", "de"] as const;

export type Lang = (typeof langs)[number];

export const langNames: Record<Lang, string> = {
  fr: "Français",
  en: "English",
  pt: "Português",
  it: "Italiano",
  de: "Deutsch",
};

const storageKey = "myinfra-lang";

export function detectLang(): Lang {
  try {
    const stored = localStorage.getItem(storageKey);
    if (isLang(stored)) return stored;
  } catch {
    /* la langue du navigateur sert */
  }
  const nav = typeof navigator === "undefined" ? "" : navigator.language.slice(0, 2).toLowerCase();
  if (isLang(nav)) return nav;
  return "fr";
}

export function isLang(value: string | null | undefined): value is Lang {
  return langs.includes(value as Lang);
}

let current: Lang = detectLang();
const listeners = new Set<() => void>();

const locales: Record<Lang, string> = { fr: "fr-FR", en: "en-GB", pt: "pt-PT", it: "it-IT", de: "de-DE" };

export function currentLocale(): string {
  return locales[currentLang()];
}

export function currentLang(): Lang {
  return current;
}

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem(storageKey, lang);
  } catch {
    /* le choix reste sur cette page */
  }
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  listeners.forEach((listen) => listen());
}

export function subscribeLang(listen: () => void) {
  listeners.add(listen);
  return () => {
    listeners.delete(listen);
  };
}

