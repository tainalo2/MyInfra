const tables: Record<Lang, Record<MsgKey, string>> = { fr, en, pt, it, de };

export function text(key: MsgKey, params?: Record<string, string | number>): string {
  let value = tables[current][key] ?? tables.fr[key];
  if (params) {
    for (const [name, param] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(param));
    }
  }
  return value;
}

export function knownMessage(message: string): string {
  const keys = Object.keys(fr) as MsgKey[];
  for (const key of keys) {
    if (key.startsWith("err.") && fr[key] === message) return text(key);
  }
  return message;
}

export function textError(code: string | undefined, params: Record<string, string> | undefined, fallback: string): string {
  if (!code) return fallback ? knownMessage(fallback) : text("common.error");
  const key = `err.${code}` as MsgKey;
  if (!(key in fr)) return fallback ? knownMessage(fallback) : text("common.error");
  return text(key, params);
}

